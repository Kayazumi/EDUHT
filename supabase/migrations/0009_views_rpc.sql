-- [DB] View chỉ báo tiến trình và các thủ tục RPC nghiệp vụ · tài liệu mục 4.4 và 7.4 · TODO: hiện thực DDL ở giai đoạn sau
-- Danh sách đối tượng sẽ tạo trong tệp này:
-- 1. View: v_task_status (tính toán is_late, is_determined theo định nghĩa mục 7.2)
-- 2. View: v_group_progress (tổng hợp tỷ lệ hoàn thành, trễ hạn từng nhóm)
-- 3. View: v_student_contribution (tổng hợp chỉ báo tiến trình cá nhân)
-- 4. View: v_group_members (hiển thị thành viên cùng nhóm cho học sinh với security_invoker = false)
-- 5. RPC: mark_password_changed() (học sinh tự bỏ cờ must_change_password)
-- 6. RPC: admin_db_size() (admin theo dõi dung lượng CSDL trên 500MB)
-- 7. RPC: instantiate_group_tasks(project_id) (sinh thẻ việc cho các nhóm đã khóa)
-- 8. RPC: set_project_status(project_id, status) (kiểm tra 5 điều kiện kích hoạt dự án)
-- 9. RPC: open_round(round_id) (mở đợt đánh giá BARS)
-- 10. RPC: submit_review(review_id) (học sinh nộp phiếu đánh giá)
-- 11. RPC: finalize_round(round_id) (đóng đợt, tính và chụp peer_scores)
-- 12. RPC: compute_final_scores(project_id, round_id) (tính Điểm_CN và chụp snapshot tiến trình)
-- 13. RPC: adjust_final_score(...) (giáo viên chỉnh điểm kèm lý do tối thiểu 10 ký tự)
-- 14. RPC: publish_results(project_id) (công bố kết quả điểm cho học sinh)
-- 15. RPC: unpublish_results(project_id, reason) (thu hồi công bố điểm để rà soát)
-- 16. RPC: record_consent(...) (giáo viên ghi nhận phiếu đồng ý nghiên cứu)
-- 17. RPC: get_my_results(project_id) (học sinh xem điểm và nhận xét của chính mình)
-- 18. RPC: export_research_dataset(project_id) (admin xuất dữ liệu giả danh cho nghiên cứu)
